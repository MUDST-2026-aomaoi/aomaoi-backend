CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL CONSTRAINT uk_users_username UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    is_first_login BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE farm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    location VARCHAR(255),
    image TEXT,
    worker_count INTEGER DEFAULT 0,
    admin_count INTEGER DEFAULT 0,
    monthly_wages DOUBLE PRECISION DEFAULT 0.0,
    total_wages DOUBLE PRECISION DEFAULT 0.0,
    status VARCHAR(255) DEFAULT 'active',
    joined_date DATE
);

CREATE TABLE worker (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255),
    nickname VARCHAR(255),
    phone VARCHAR(255),
    avatar TEXT,
    status VARCHAR(255) DEFAULT 'active',
    farm_id BIGINT,
    joined_date DATE,
    user_id BIGINT CONSTRAINT uk_worker_user UNIQUE,
    CONSTRAINT fk_worker_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_worker_farm FOREIGN KEY (farm_id) REFERENCES farm(id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE admin_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255),
    phone VARCHAR(255),
    farm_id BIGINT,
    avatar TEXT,
    status VARCHAR(255) DEFAULT 'pending',
    joined_date DATE,
    user_id BIGINT CONSTRAINT uk_admin_profile_user UNIQUE,
    CONSTRAINT fk_admin_profile_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_admin_profile_farm FOREIGN KEY (farm_id) REFERENCES farm(id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE work_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    work_date DATE NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    rows INTEGER,
    wa_per_row INTEGER,
    furrows INTEGER,
    wa_per_furrow INTEGER,
    days INTEGER,
    daily_rate NUMERIC(38, 2),
    tanks INTEGER,
    total NUMERIC(38, 2) NOT NULL,
    CONSTRAINT fk_work_logs_worker FOREIGN KEY (worker_id) REFERENCES worker(id)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(255) NOT NULL,
    performed_by VARCHAR(255) NOT NULL,
    target_user VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    details TEXT
);

CREATE INDEX idx_worker_farm_id ON worker(farm_id);
CREATE INDEX idx_admin_profile_farm_id ON admin_profile(farm_id);
CREATE INDEX idx_work_logs_worker_date ON work_logs(worker_id, work_date DESC, id DESC);

