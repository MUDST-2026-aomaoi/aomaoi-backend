--comment: Record cash and goods advances without rewriting historical work logs.
CREATE TABLE salary_advances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES worker(id) ON DELETE RESTRICT,
    advance_date DATE NOT NULL,
    type VARCHAR(16) NOT NULL CHECK (type IN ('CASH', 'GOODS')),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    item_name VARCHAR(255),
    recorded_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancelled_at TIMESTAMPTZ,
    cancelled_by VARCHAR(255),
    e2e_run_id VARCHAR(36) REFERENCES e2e_runs(id),
    CONSTRAINT ck_salary_advance_details CHECK (
        (type = 'CASH' AND item_name IS NULL) OR
        (type = 'GOODS' AND item_name IS NOT NULL AND btrim(item_name) <> '')
    ),
    CONSTRAINT ck_salary_advance_cancellation CHECK (
        (cancelled_at IS NULL AND cancelled_by IS NULL) OR
        (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL)
    )
);
CREATE INDEX idx_salary_advances_worker_date ON salary_advances(worker_id, advance_date DESC, id DESC);
CREATE INDEX idx_salary_advances_e2e_run ON salary_advances(e2e_run_id);

CREATE FUNCTION aomaoi_salary_advance_e2e_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    run_id TEXT := NULLIF(current_setting('aomaoi.e2e_run', true), '');
    worker_run TEXT;
BEGIN
    IF TG_OP <> 'INSERT' AND OLD.e2e_run_id IS DISTINCT FROM run_id THEN
        RAISE EXCEPTION 'E2E ownership mismatch: cannot modify salary advance outside this run';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    SELECT e2e_run_id INTO worker_run FROM worker WHERE id = NEW.worker_id;
    IF worker_run IS DISTINCT FROM run_id THEN
        RAISE EXCEPTION 'E2E worker ownership mismatch';
    END IF;
    NEW.e2e_run_id := run_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER e2e_guard BEFORE INSERT OR UPDATE OR DELETE ON salary_advances
    FOR EACH ROW EXECUTE FUNCTION aomaoi_salary_advance_e2e_guard();

