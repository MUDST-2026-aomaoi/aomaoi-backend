--comment: Per-worker, per-day attendance (PRESENT / LEAVE / ABSENT). No row means "not checked yet". Rows created by the 18:00 close-day job are flagged auto_recorded.
CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES worker(id) ON DELETE RESTRICT,
    attendance_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PRESENT', 'LEAVE', 'ABSENT')),
    note VARCHAR(255),
    auto_recorded BOOLEAN NOT NULL DEFAULT false,
    recorded_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    e2e_run_id VARCHAR(36) REFERENCES e2e_runs(id),
    CONSTRAINT uq_attendance_worker_date UNIQUE (worker_id, attendance_date)
);
CREATE INDEX idx_attendance_date ON attendance(attendance_date);
CREATE INDEX idx_attendance_e2e_run ON attendance(e2e_run_id);

-- Same ownership rules as the other worker-owned tables: during an E2E run only that run's
-- workers can be touched, and new rows are tagged with the run.
CREATE FUNCTION aomaoi_attendance_e2e_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    run_id TEXT := NULLIF(current_setting('aomaoi.e2e_run', true), '');
    worker_run TEXT;
BEGIN
    IF TG_OP <> 'INSERT' AND OLD.e2e_run_id IS DISTINCT FROM run_id THEN
        RAISE EXCEPTION 'E2E ownership mismatch: cannot modify attendance outside this run';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    SELECT e2e_run_id INTO worker_run FROM worker WHERE id = NEW.worker_id;
    IF worker_run IS DISTINCT FROM run_id THEN
        RAISE EXCEPTION 'E2E worker ownership mismatch';
    END IF;
    NEW.e2e_run_id := run_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER e2e_guard BEFORE INSERT OR UPDATE OR DELETE ON attendance
    FOR EACH ROW EXECUTE FUNCTION aomaoi_attendance_e2e_guard();

-- A worker's farm can no longer change once attendance exists either (history belongs to the farm).
-- Separate from the 006 guard so this changeset can be rolled back with plain DROP statements.
CREATE FUNCTION aomaoi_guard_worker_farm_change_attendance() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.farm_id IS DISTINCT FROM OLD.farm_id AND EXISTS (SELECT 1 FROM attendance WHERE worker_id = OLD.id) THEN
        RAISE EXCEPTION 'Cannot change farm after attendance exists for worker %', OLD.id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER guard_worker_farm_change_attendance BEFORE UPDATE OF farm_id ON worker
    FOR EACH ROW EXECUTE FUNCTION aomaoi_guard_worker_farm_change_attendance();

